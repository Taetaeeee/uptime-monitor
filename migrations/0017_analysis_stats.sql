-- 0017: 점검 기록 분석용 일별 집계 열 (16단계)
--
-- 서비스 상세 화면에 세 가지 분석을 더합니다.
--   ① 실패 이유 분포   — 실패가 시간 초과인지, 상태 코드인지, DNS인지
--   ② p95 응답 시간     — 평균 대신 "느린 쪽 5%"의 경계값 (일별 추이)
--   ③ 시간대 열지도     — 요일 × 시간(KST)별 실패·느림 비율
--
-- 왜 새 테이블이 아니라 daily_stats에 열을 더하나?
--   화면을 열 때마다 원본(점검당 하루 288행)을 30일치 읽으면 D1 읽기 한도를 금방 씁니다.
--   Cron은 이미 매 회차 오늘·어제 원본을 읽어 daily_stats를 다시 계산하므로(src/record.js),
--   그때 같은 원본으로 분석 값도 함께 계산해 두면 추가 읽기가 없어요.
--   시간대별 값을 '시간당 1행' 표로 두면 30일 × 24시간 × 점검 수만큼 읽어야 하지만,
--   하루 1행 안에 24칸짜리 JSON으로 두면 기존처럼 점검당 30행만 읽으면 됩니다.
--   (정규화보다 읽기 비용을 우선한 선택 — 이 값은 화면 표시용 요약이라 조건 검색할 일이 없음)
--
-- 과거 기록은 이 마이그레이션에서 채우지 않습니다.
--   p95를 SQL로 구하려면 윈도 함수(ROW_NUMBER() OVER)가 필요한데, D1 공식 문서에 지원 여부가 적혀 있지 않습니다.
--   대신 Cron이 회차마다 분석 값이 비어 있는(hourly IS NULL) 날을 몇 개씩 원본에서 다시 계산해 채웁니다.
--   계산 규칙이 순수 함수 하나(src/analysis.js analyzeDay)에만 있어서 과거·현재 값이 같은 규칙으로 만들어져요.

-- 성공한 점검의 p95 응답 시간(ms). 성공이 없으면 NULL
ALTER TABLE daily_stats ADD COLUMN p95_response_ms INTEGER;

-- 시간대별 [전체, 실패, 느림] 24칸 JSON. 칸 번호 = 한국 시각(0~23시)
-- 예: [[12,0,1],[12,0,0],...]  NULL이면 "아직 분석 안 함" (Cron이 나중에 채움)
ALTER TABLE daily_stats ADD COLUMN hourly TEXT;

-- 실패 이유별 횟수 JSON. 예: {"timeout":2,"dns_error":1}  실패가 없으면 {}
ALTER TABLE daily_stats ADD COLUMN failures TEXT;
