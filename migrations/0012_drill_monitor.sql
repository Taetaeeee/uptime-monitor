-- 0012: 장애 훈련 전용 점검 대상 1개 — 비활성(is_active = 0)으로 등록
--
-- 왜 필요한가?
--   "일부러 장애를 내고 → 알림 → 복구 → 사후 보고서"를 실제 서비스(고쳐라!, Keychats)를 건드리지 않고 해 보려는 훈련용입니다.
--   내 PC에서 테스트 서버(127.0.0.1:18080)를 켜 두고 Python 에이전트(실제 모드)가 그 포트의 연결 여부를 5분마다 보고합니다.
--   테스트 서버를 끄면 "포트 연결 실패"가 2회 연속 → 장애 판정, 다시 켜면 복구입니다.
--
-- 왜 source = 'real' 인가?
--   에이전트 실제 모드(mode: "real")의 보고는 서버가 'real' 대상에만 기록합니다(가짜 값이 섞이지 않게 하는 규칙).
--   이 포트를 정말로 끄고 켜는 것이라 가짜 측정값이 아닙니다. 대신 이름에 '훈련'을 넣고 사후 보고서에도 훈련이라고 적습니다.
--
-- 왜 비활성으로 시작하나?
--   에이전트가 돌지 않는 평소에는 이 카드가 '확인 중'으로 남아 헷갈리기 때문입니다.
--   훈련 직전에 켜고, 끝나면 다시 꺼서 '점검 대기'로 둡니다. (장애 이력·보고서·계획 작업 기록은 화면에 계속 남습니다)
--
-- 공개 화면에는 이 대상의 이름과 상태만 보이고, 주소(127.0.0.1:18080)는 공개 응답에 들어가지 않습니다.
--
